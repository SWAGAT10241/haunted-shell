"""
Generates terminal UI screenshots (SVG) and formatted Markdown previews for PRs and documentation.
Uses Rich Console recording to export a realistic dark terminal window.
"""

import os
from pathlib import Path
from rich.console import Console
from rich.text import Text

from haunted_shell.ui import get_banner
from haunted_shell.ghost import GhostEngine
from haunted_shell.exorcist import Exorcist


def generate_preview():
    output_dir = Path("docs/assets")
    output_dir.mkdir(parents=True, exist_ok=True)
    svg_path = output_dir / "ui_preview.svg"
    md_path = output_dir / "ui_preview.md"

    console = Console(record=True, width=105, color_system="truecolor")

    console.print("[bold purple]👻 haunted-shell — Terminal UI & Modifier Snapshot[/bold purple]")
    console.print("[dim]Generated automatically by CI for UI inspection[/dim]\n")

    # 1. Banners
    console.print("[bold yellow]─── [1] Día de los Muertos & Halloween Banners ───[/bold yellow]")
    console.print(Text.from_ansi(get_banner("poltergeist")))
    console.print(Text.from_ansi(get_banner("calavera")))

    # 2. Command reactions
    console.print("[bold cyan]─── [2] Spectral Command Reactions & Tone Modifiers ───[/bold cyan]\n")

    samples = [
        ("poltergeist", [], "rm -rf old_secrets.txt"),
        ("calavera", [], "git commit -m 'Initial commit'"),
        ("unix-elder", [], "git push --force origin main"),
        ("poltergeist", ["matrix", "eldritch"], "cargo build --release"),
        ("poltergeist", ["vaporwave"], "whoami"),
        ("poltergeist", ["cursed"], "docker run -d redis"),
    ]

    for persona, mods, cmd in samples:
        engine = GhostEngine(force_offline=True, persona_name=persona, modifiers=mods, glitch_intensity=1)
        whisper = engine.haunt_command(cmd)
        mod_tag = f" [dim]({'+'.join(mods)})[/dim]" if mods else ""
        console.print(f"[bold green]$ {cmd}[/bold green]{mod_tag}")
        console.print(f"  {Text.from_ansi(whisper)}\n")

    # 3. Exorcist Report
    console.print("[bold red]─── [3] Kernel Zombie Process Exorcism ───[/bold red]\n")
    exorcist = Exorcist()
    sample_spirits = [
        {
            "pid": 34646,
            "name": "Code Helper (Renderer)",
            "type": "Memory Wraith",
            "age_min": 36.2,
            "mem_mb": 200.7,
            "epitaph": "Devours physical memory like a restless devourer.",
            "danger": "LOW",
        },
        {
            "pid": 41047,
            "name": "language_server",
            "type": "Shadow Daemon",
            "age_min": 8.3,
            "mem_mb": 201.7,
            "epitaph": "Spawned in haste, abandoned in cold memory.",
            "danger": "MEDIUM",
        },
    ]

    # Capture exorcist box lines
    from haunted_shell.ui import spectral_box
    spectral_box_lines = [
        f"Detected {len(sample_spirits)} restless entity/entities lurking in memory:",
        "",
        "• PID 34646 [Memory Wraith] - Code Helper (Renderer)",
        "  Memory: 200.7 MB | Age: 36.2 mins",
        '  "Devours physical memory like a restless devourer."',
        "",
        "• PID 41047 [Shadow Daemon] - language_server",
        "  Memory: 201.7 MB | Age: 8.3 mins",
        '  "Spawned in haste, abandoned in cold memory."',
    ]
    from io import StringIO
    import sys
    old_stdout = sys.stdout
    sys.stdout = buffer = StringIO()
    spectral_box("SPECTRAL PROCESS NECROPSY", spectral_box_lines, color="\033[38;5;196m")
    sys.stdout = old_stdout
    console.print(Text.from_ansi(buffer.getvalue()))

    # Save SVG Screenshot
    console.save_svg(str(svg_path), title="haunted-shell Terminal UI Preview")
    print(f"✓ Saved UI SVG Screenshot to {svg_path}")

    # Generate Markdown preview for PR comment
    md_content = f"""### 🎨 Automated Terminal UI Preview & Screenshot

This pull request includes visual UI / terminal output changes. Below is the automated terminal screenshot and output snapshot:

<details open>
<summary><b>🖥️ Terminal UI Snapshot Preview</b></summary>

```console
[haunted-shell] 👻 rm -rf old_secrets.txt
  👻 Gone. Banished to /dev/null. But in the graveyard of your disk, their sectors still whisper.

[haunted-shell] 💀 git commit -m 'Initial commit'
  💀 Estaba la Catrina sentada en el disco / viendo tus commits con sonrisa y pellizco:
     '¡No te apures, dev, por ese merge conflict / que en el camposanto todo queda fixed!'

[haunted-shell] 👻 (matrix+eldritch) cargo build --release
  👻 Ph'nglui mglw'nafh... The Borrow Checker is the ｵharshest reaper of all...

[haunted-shell] 👻 (vaporwave) whoami
  👻 Ｙｏｕ　ａｒｅ　ｍｅｒｅｌｙ　ａ　ｇｕｅｓｔ　ｕｓｅｒ...
```

</details>

*Generated by CI for commit `{os.environ.get('GITHUB_SHA', 'local')[:7]}`*
"""
    with open(md_path, "w", encoding="utf-8") as f:
        f.write(md_content)
    print(f"✓ Saved PR Markdown preview to {md_path}")


if __name__ == "__main__":
    generate_preview()
